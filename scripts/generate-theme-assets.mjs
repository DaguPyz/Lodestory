import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = async path => JSON.parse(await readFile(new URL(path, root), "utf8"));
const registry = await read("src/plugins/theme/color-registry.json");
const definitions = await Promise.all(["dark", "light"].map(type => read(`src/plugins/builtin-themes/${type}.theme.json`)));
const config = await read("src/plugins/theme/theme-config.json");
for (const type of ["dark", "light"]) {
  if (!definitions.some(theme => theme.id === config.fallbackThemeIds[type] && theme.type === type)) throw new Error(`Missing ${type} first-paint fallback.`);
}
if (!definitions.some(theme => theme.id === config.defaultThemeId)) throw new Error("Missing first-paint default theme.");
const roles = new Map(registry.colors.map(role => [role.id, role]));
function resolveTheme(theme) {
  const colors = {};
  const visiting = new Set();
  function resolve(id) {
    if (Object.hasOwn(colors, id)) return colors[id];
    if (visiting.has(id)) throw new Error(`Circular theme default: ${id}`);
    visiting.add(id);
    const fallback = roles.get(id).defaults[theme.type];
    colors[id] = theme.colors[id] ?? (typeof fallback === "string" ? fallback : resolve(fallback.ref));
    visiting.delete(id);
    return colors[id];
  }
  const variables = Object.fromEntries(registry.colors.map(role => [role.cssVariable, resolve(role.id)]));
  for (const recipe of registry.shadowRecipes) {
    variables[recipe.cssVariable] = recipe.layers.map(layer => `${layer.x}px ${layer.y}px ${layer.blur}px ${layer.spread}px ${colors[layer.color]}`).join(", ");
  }
  variables["--ui-color-scheme"] = theme.type;
  return { ...theme, colors, variables };
}
const themes = definitions.map(resolveTheme);
const css = "/* Generated by scripts/generate-theme-assets.mjs. Edit src/plugins/builtin-themes/*.theme.json. */\n" + themes.map(theme =>
  `\n${theme.id === config.defaultThemeId ? ":root,\n" : ""}[data-ui-theme-id="${theme.id}"] {\n${Object.entries(theme.variables).map(([key, value]) => `  ${key}: ${value};`).join("\n")}\n}\n`
).join("");
await writeFile(new URL("src/styles/theme-colors.css", root), css);
await writeFile(new URL("packages/sdk/src/themeColors.ts", root), "// Generated from src/plugins/theme/color-registry.json.\nexport type ThemeColorId =\n" + registry.colors.map(role => `  | ${JSON.stringify(role.id)}`).join("\n") + ";\n");
const template = await readFile(new URL("scripts/theme-bootstrap.template.js", root), "utf8");
const catalog = themes.map(theme => ({ id: theme.id, type: theme.type, background: theme.colors["surface.content"] }));
await writeFile(new URL("public/theme-bootstrap.js", root), "/* Generated by scripts/generate-theme-assets.mjs. */\n" + template.replace("/* THEME_CATALOG */ []", JSON.stringify(catalog)).replace("/* THEME_CONFIG */ {}", JSON.stringify(config)));
